#!/usr/bin/env node
/**
 * Generates THIRD_PARTY_NOTICES.md from the PRODUCTION dependency tree.
 *
 *   npm run notices
 *
 * Why generated: `dist/bundle.js` (the .mcpb entry point) inlines every runtime
 * dependency, and the .mcpb ships no node_modules — so the license and notice
 * texts those packages require to accompany a copy have to travel in this one
 * file. A hand-kept table listed 9 of ~38 packages and pointed at npm for the
 * texts, which a .mcpb user never sees.
 *
 * Source of truth: package-lock.json's `packages` map. A package is
 * "production" unless the lockfile marks it `dev` or `devOptional` (the
 * latter are dev tools that are also OPTIONAL peers of a runtime package —
 * e.g. vitest for mcp-utils' test helpers — and are not installed for a user).
 * That is a superset of what esbuild actually bundles, which is the safe
 * direction for a notices file. For each package: name, version, license,
 * repository, and the full text of every LICENSE / LICENCE / COPYING / NOTICE
 * file it ships, read from node_modules (run `npm ci` first).
 *
 * It also runs as the first step of `npm run bundle` (so of `npm run build`),
 * which is what makes the SHIPPED copy correct: CI and the publish job build
 * from the lockfile they install, so the npm package and the .mcpb always
 * carry the notices of the dependencies they actually contain — including
 * right after a Dependabot bump, which never runs this script itself (with the
 * file only generated by hand, every weekly runtime-dependency PR went red).
 * Commit the regenerated file when a build changes it.
 *
 * The output is deterministic (sorted, no timestamps), is written only when it
 * changed, and is replaced atomically (a test may be reading it while
 * tests/server-boot.test.ts builds). tests/third-party-notices.test.ts fails
 * when the file does not match the installed tree.
 */
import { existsSync, readdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const OUTPUT_FILE = 'THIRD_PARTY_NOTICES.md';

const LICENSE_FILE = /^(licen[cs]e|copying|notice)([.\-_].*)?$/i;

/** Every production package in a parsed package-lock.json (lockfileVersion 2/3), sorted by name then version. */
export function productionPackages(lock) {
  const out = [];
  for (const [path, entry] of Object.entries(lock.packages ?? {})) {
    if (path === '' || entry.dev || entry.devOptional || entry.link) continue;
    const name = entry.name ?? path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length);
    out.push({ path, name, version: entry.version, license: entry.license, optional: entry.optional === true });
  }
  return out.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, 'en', { numeric: true }));
}

/** A browsable https URL for a package.json `repository`, or undefined. */
export function repositoryUrl(pkg) {
  const raw = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  if (!raw) return typeof pkg.homepage === 'string' ? pkg.homepage : undefined;
  let url = raw.trim();
  const shorthand = /^(?:(github|gitlab|bitbucket):)?([\w.-]+\/[\w.-]+)$/.exec(url);
  if (shorthand) {
    const host = { github: 'github.com', gitlab: 'gitlab.com', bitbucket: 'bitbucket.org' }[shorthand[1] ?? 'github'];
    return `https://${host}/${shorthand[2]}`;
  }
  url = url
    .replace(/^git\+/, '')
    .replace(/^git:\/\//, 'https://')
    .replace(/^ssh:\/\/git@/, 'https://')
    .replace(/^git@([^:]+):/, 'https://$1/')
    .replace(/\.git$/, '');
  return url;
}

function licenseOf(entry, pkg) {
  if (entry.license) return entry.license;
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license && typeof pkg.license.type === 'string') return pkg.license.type;
  return 'UNKNOWN';
}

/** A fence longer than any backtick run inside `text`. */
function fenceFor(text) {
  const longest = Math.max(0, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
  return '`'.repeat(Math.max(3, longest + 1));
}

/** The collected facts and texts for one package. */
function collect(root, entry) {
  const dir = join(root, entry.path);
  if (!existsSync(join(dir, 'package.json'))) {
    if (entry.optional) {
      return { ...entry, license: entry.license ?? 'UNKNOWN', repository: undefined, files: [], missing: true };
    }
    throw new Error(`${entry.path} is not installed; run \`npm ci\` before \`npm run notices\`.`);
  }
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const files = readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => ({ name: f, text: readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trimEnd() }));
  return { ...entry, license: licenseOf(entry, pkg), repository: repositoryUrl(pkg), files, missing: false };
}

/** The whole THIRD_PARTY_NOTICES.md, from the lockfile and node_modules under `root`. */
export function renderNotices(root = ROOT) {
  const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
  const packages = productionPackages(lock).map((entry) => collect(root, entry));
  const ical = packages.find((p) => p.name === 'ical.js');
  const lines = [
    '# Third-party notices',
    '',
    '<!-- Generated by `npm run notices` and by every `npm run build` (scripts/third-party-notices.mjs) from',
    '     package-lock.json and node_modules. Do not edit by hand: tests/third-party-notices.test.ts fails when this',
    '     file drifts from the installed dependencies. -->',
    '',
    '`apple-icloud-mcp` itself is MIT-licensed (see `LICENSE`). Its npm package depends on, and `dist/bundle.js`',
    '(the `.mcpb` entry point, which ships without `node_modules`) contains code from, the third-party packages',
    'below. This is the complete production dependency tree from `package-lock.json` — a superset of what the',
    'bundle actually includes. Each package remains under its own license, and the full text of every license and',
    'notice file each one ships is reproduced in this file.',
    '',
  ];
  if (ical) {
    lines.push(
      '## ical.js (MPL-2.0): source code',
      '',
      `\`dist/bundle.js\` contains ical.js ${ical.version}, unmodified, under the Mozilla Public License 2.0 ` +
        '(https://mozilla.org/MPL/2.0/).',
      `Its Source Code Form is available from the \`ical.js\` package on npm ` +
        `(https://www.npmjs.com/package/ical.js/v/${ical.version}) and from ${ical.repository ?? 'https://github.com/kewisch/ical.js'} ` +
        `(version ${ical.version}).`,
      "MPL-2.0 is a file-level license: it covers ical.js's own files and does not extend to the rest of this project.",
      '',
    );
  }
  lines.push('## Packages', '', `${packages.length} packages.`, '', '| Package | Version | License | Source |', '|---|---|---|---|');
  for (const p of packages) {
    lines.push(`| ${p.name} | ${p.version} | ${p.license} | ${p.repository ?? '—'} |`);
  }
  lines.push('', '## License and notice texts', '');
  for (const p of packages) {
    lines.push(`### ${p.name}@${p.version}`, '', `- License: ${p.license}`);
    if (p.repository) lines.push(`- Source: ${p.repository}`);
    lines.push('');
    if (p.missing) {
      lines.push('_An optional dependency that was not installed where this file was generated; see its package on npm._', '');
      continue;
    }
    if (p.files.length === 0) {
      lines.push(`_This package ships no license file; its package.json declares ${p.license}._`, '');
      continue;
    }
    for (const f of p.files) {
      const fence = fenceFor(f.text);
      lines.push(`\`${f.name}\`:`, '', `${fence}text`, f.text, fence, '');
    }
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function main() {
  const text = renderNotices(ROOT);
  const target = join(ROOT, OUTPUT_FILE);
  const count = (text.match(/^### /gm) ?? []).length;
  if (existsSync(target) && readFileSync(target, 'utf8') === text) {
    console.error(`${OUTPUT_FILE} is up to date (${count} packages).`);
    return;
  }
  const tmp = `${target}.tmp-${process.pid}`;
  writeFileSync(tmp, text);
  renameSync(tmp, target);
  console.error(`Wrote ${OUTPUT_FILE}: ${count} packages. Commit it.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main();
